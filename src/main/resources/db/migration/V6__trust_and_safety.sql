-- Trust and safety: member blocks, reports, and account suspension by moderators.

ALTER TABLE users
    ADD COLUMN suspended_at      TIMESTAMPTZ,
    ADD COLUMN suspension_reason VARCHAR(500);
-- A suspension always records why (shown to the member and to other moderators).
ALTER TABLE users ADD CONSTRAINT ck_users_suspension CHECK ((suspended_at IS NULL) = (suspension_reason IS NULL));

-- A block stops the blocked member from messaging, making offers to or requesting items from the blocker,
-- and the other way round.
CREATE TABLE user_blocks (
    blocker_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT ck_user_blocks_distinct CHECK (blocker_id <> blocked_id)
);
CREATE INDEX idx_user_blocks_blocked ON user_blocks (blocked_id);

CREATE TABLE reports (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id       BIGINT        NOT NULL REFERENCES users (id),
    target_type       VARCHAR(20)   NOT NULL,
    reported_user_id  BIGINT        NOT NULL REFERENCES users (id),
    item_id           BIGINT REFERENCES items (id),
    message_id        BIGINT REFERENCES messages (id),
    reason            VARCHAR(30)   NOT NULL,
    details           VARCHAR(1000),
    -- What the reporter saw, captured when the report is filed, so later edits cannot hide the evidence.
    evidence          VARCHAR(4200) NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    resolution        VARCHAR(30),
    resolution_note   VARCHAR(500),
    resolved_by_id    BIGINT REFERENCES users (id),
    resolved_at       TIMESTAMPTZ,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_reports_target_type CHECK (target_type IN ('USER', 'ITEM', 'MESSAGE')),
    -- Exactly the reference the target type needs (NULL passes a CHECK, so IS NOT NULL is spelled out).
    CONSTRAINT ck_reports_target_ref CHECK (
        (target_type = 'USER' AND item_id IS NULL AND message_id IS NULL)
        OR (target_type = 'ITEM' AND item_id IS NOT NULL AND message_id IS NULL)
        OR (target_type = 'MESSAGE' AND message_id IS NOT NULL AND item_id IS NULL)),
    CONSTRAINT ck_reports_reason CHECK (reason IN
        ('SCAM', 'PROHIBITED_ITEM', 'FAKE_LISTING', 'HARASSMENT', 'SPAM', 'INAPPROPRIATE', 'OTHER')),
    CONSTRAINT ck_reports_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_reports_resolution CHECK (resolution IS NULL OR resolution IN
        ('DISMISSED', 'ITEM_REMOVED', 'USER_SUSPENDED')),
    -- Open reports carry no outcome; resolved ones record what was decided, by whom and when.
    CONSTRAINT ck_reports_lifecycle CHECK (
        (status = 'OPEN' AND resolution IS NULL AND resolved_by_id IS NULL AND resolved_at IS NULL)
        OR (status = 'RESOLVED' AND resolution IS NOT NULL AND resolved_by_id IS NOT NULL
            AND resolved_at IS NOT NULL)),
    CONSTRAINT ck_reports_not_self CHECK (reporter_id <> reported_user_id)
);
-- One open report per reporter and target.
CREATE UNIQUE INDEX uk_reports_open_target ON reports
    (reporter_id, target_type, reported_user_id, COALESCE(item_id, 0), COALESCE(message_id, 0))
    WHERE status = 'OPEN';
CREATE INDEX idx_reports_queue ON reports (status, created_at);
CREATE INDEX idx_reports_reported_user ON reports (reported_user_id, status);
CREATE INDEX idx_reports_item ON reports (item_id, status) WHERE item_id IS NOT NULL;
CREATE INDEX idx_reports_reporter ON reports (reporter_id, status);
