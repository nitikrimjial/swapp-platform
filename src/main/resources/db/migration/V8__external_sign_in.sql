-- Sign in with Google (and any later provider). A member is matched on the provider's stable subject id, never on
-- the email address, because the email on a Google account can change.

-- Members who joined with Google have no password until they choose to set one.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- A deleted account now keeps no password hash at all (previously an unusable random one).
UPDATE users SET password_hash = NULL WHERE deleted_at IS NOT NULL;
ALTER TABLE users DROP CONSTRAINT ck_users_deleted_erased;
ALTER TABLE users ADD CONSTRAINT ck_users_deleted_erased CHECK (
    deleted_at IS NULL OR (
        bio IS NULL AND location IS NULL AND avatar_key IS NULL AND latitude IS NULL AND longitude IS NULL
        AND email_verified_at IS NULL AND password_hash IS NULL AND email LIKE 'deleted-%@deleted.invalid'
    )
);

CREATE TABLE user_identities (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider      VARCHAR(20)  NOT NULL,
    -- The provider's permanent account id ("sub" claim).
    subject       VARCHAR(255) NOT NULL,
    -- Email on the provider account when last used; shown in Settings and the data export.
    email         VARCHAR(255) NOT NULL,
    last_used_at  TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    -- One Swapp account per provider account, and one provider account of each kind per member.
    CONSTRAINT uk_user_identities_subject UNIQUE (provider, subject),
    CONSTRAINT uk_user_identities_user_provider UNIQUE (user_id, provider),
    CONSTRAINT ck_user_identities_provider CHECK (provider IN ('GOOGLE'))
);
