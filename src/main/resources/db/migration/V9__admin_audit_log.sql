-- Staff audit log: one row for every action a moderator or admin takes (who, what, to whom, when, why).

CREATE TABLE admin_audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id        BIGINT      NOT NULL REFERENCES users (id),
    action          VARCHAR(30) NOT NULL,
    -- The member affected: the suspended or reinstated member, the listing's owner, or the reported member.
    -- Only ids are stored, never names or emails, so erasing an account also anonymises its audit entries.
    target_user_id  BIGINT      NOT NULL REFERENCES users (id),
    item_id         BIGINT REFERENCES items (id),
    report_id       BIGINT REFERENCES reports (id),
    note            VARCHAR(500),
    created_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_admin_audit_action CHECK (action IN
        ('REPORT_DISMISSED', 'LISTING_REMOVED', 'MEMBER_SUSPENDED', 'MEMBER_REINSTATED')),
    -- A takedown always names the listing (NULL passes a CHECK, so IS NOT NULL is spelled out).
    CONSTRAINT ck_admin_audit_listing CHECK (action <> 'LISTING_REMOVED' OR item_id IS NOT NULL),
    CONSTRAINT ck_admin_audit_dismissal CHECK (action <> 'REPORT_DISMISSED' OR report_id IS NOT NULL)
);
CREATE INDEX idx_admin_audit_created ON admin_audit_log (created_at DESC, id DESC);
CREATE INDEX idx_admin_audit_target_user ON admin_audit_log (target_user_id, created_at DESC);
CREATE INDEX idx_admin_audit_actor ON admin_audit_log (actor_id, created_at DESC);

-- The log is append-only: entries can be added, but never changed or deleted, not even by the application.
CREATE FUNCTION admin_audit_log_append_only() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'admin_audit_log is append-only' USING ERRCODE = 'integrity_constraint_violation';
END
$$;

CREATE TRIGGER trg_admin_audit_log_append_only
    BEFORE UPDATE OR DELETE ON admin_audit_log
    FOR EACH ROW EXECUTE FUNCTION admin_audit_log_append_only();

-- Staff search members by name or email ("contains"), so give those the same trigram indexes listings have.
CREATE INDEX idx_users_display_name_trgm ON users USING gin (lower(display_name) gin_trgm_ops);
CREATE INDEX idx_users_email_trgm ON users USING gin (lower(email) gin_trgm_ops);
CREATE INDEX idx_users_created ON users (created_at);
CREATE INDEX idx_reports_created ON reports (created_at);
