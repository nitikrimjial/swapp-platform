-- Email verification and single-use account tokens (email verification, password reset).

ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMPTZ;
-- Accounts created before verification existed are treated as verified.
UPDATE users SET email_verified_at = created_at;

-- Only a SHA-256 hash of each token is stored, so a database leak does not expose usable links.
CREATE TABLE user_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     VARCHAR(30) NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_user_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_user_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    CONSTRAINT ck_user_tokens_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_user_tokens_user_purpose ON user_tokens (user_id, purpose) WHERE used_at IS NULL;
CREATE INDEX idx_user_tokens_expires ON user_tokens (expires_at);
